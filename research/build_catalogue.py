def link(ev):
    if ev.startswith("repo:"):
        return {"file": "Runway today", "code": "repo", "node": ev[5:], "url": ""}
    code, node = ev.split(":", 1)
    name, key = FILES[code]
    return {"file": name, "code": code, "node": node,
            "url": f"https://www.figma.com/design/{key}/?node-id={node.replace(':', '-')}"}


def main():
    out = []
    for it in ITEMS:
        it = dict(it)
        it["evidence"] = [link(e) for e in it.get("evidence", [])]
        if "options" in it:
            oev = OPTION_EV.get(it["id"], {})
            it["options"] = [{"key": k, "label": l, "detail": d, "evidence": [link(e) for e in oev.get(k, [])]} for k, l, d in it["options"]]
        out.append(it)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "pattern-catalogue.json"), "w") as f:
        json.dump({"files": {k: {"name": v[0], "key": v[1]} for k, v in FILES.items()}, "items": out}, f, ensure_ascii=False, indent=1)
    kinds = {}
    for it in out:
        kinds[it["kind"]] = kinds.get(it["kind"], 0) + 1
    print(kinds, "images:", sum(1 for it in out if it.get("image")))


if __name__ == "__main__":
    main()
